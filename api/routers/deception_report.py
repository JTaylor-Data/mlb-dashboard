"""
/api/deception/* - serves the Deception+ v1 report (from
train_deception_model.py, read straight off disk) plus live per-pitcher
SHAP breakdowns (from deception_model.py, the trained booster scoring on
demand) for the model-internals page (deception-model.html). Same
"no black box" pattern as stuff_model_report.py/tunneling_report.py.

This is a proof-of-concept, single-season model (see train_deception_model.py's
module docstring for what's included vs. explicitly dropped) - no season
selector yet, unlike Stuff+/Tunneling+. REPORT_SEASON here must match
train_deception_model.py's REPORT_SEASON.
"""
import json
from pathlib import Path

from fastapi import APIRouter, Depends, HTTPException

from api.cache import ttl_cache
from api.db import get_conn
from analytics.deception_model import _raw_predictions, pitcher_deception_breakdown

router = APIRouter(prefix="/api/deception")

MODELS_DIR = Path(__file__).resolve().parent.parent.parent / "models"
REPORT_SEASON = 2026
REPORT_PATH = MODELS_DIR / f"deception_plus_v1_report_{REPORT_SEASON}.json"


@ttl_cache()
def _raw_predictions_table(conn, season):
    """League-wide raw predictions for one season - cached because scoring
    every pitch in a season is the expensive part; per-pitcher SHAP
    lookups below reuse this instead of re-scoring the whole league each
    time. Same pattern as stuff_model_report.py."""
    return _raw_predictions(conn, season)


@ttl_cache()
def _pitcher_breakdown_cached(conn, season, pitcher_id):
    """Per-pitcher SHAP breakdown — cached so repeated player-page loads
    and career-page loads don't re-run SHAP scoring each time."""
    league = _raw_predictions_table(conn, season)
    return pitcher_deception_breakdown(conn, season, pitcher_id, league)


@router.get("/report")
def get_report():
    """The full validation report: CV metrics, SHAP/gain feature
    importance, split-half reliability, outcome-correlation validity
    checks, worked examples, and the plain-language usefulness verdict.
    Regenerated by re-running `python train_deception_model.py`."""
    if not REPORT_PATH.exists():
        raise HTTPException(404, "No deception report found - run train_deception_model.py first")
    return json.loads(REPORT_PATH.read_text())


@router.get("/pitcher/{pitcher_id}")
def get_pitcher_breakdown(pitcher_id: int, conn=Depends(get_conn)):
    """One pitcher's Deception+ score plus a live SHAP breakdown of which
    delivery/body features are driving it, for REPORT_SEASON (this
    proof-of-concept has no season selector yet)."""
    breakdown = _pitcher_breakdown_cached(conn, REPORT_SEASON, pitcher_id)
    if not breakdown:
        raise HTTPException(404, f"No pitches found for pitcher {pitcher_id} in {REPORT_SEASON}")
    return breakdown
