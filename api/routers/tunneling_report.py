"""
/api/tunneling/* - serves the Tunneling+ v1 report (from
build_tunneling_report.py, read straight off disk) for the model-internals
page (tunneling-model.html). Same "no black box" pattern as
stuff_model_report.py: every number the page shows traces back to the
offline report or the per-pitcher detail file. One report/pitchers file
pair per season - `season` is a required query param, matching how the
frontend always resolves a season (via createSeasonSelect) before making
its first request.
"""
import json
from pathlib import Path

from fastapi import APIRouter, HTTPException

router = APIRouter(prefix="/api/tunneling")

MODELS_DIR = Path(__file__).resolve().parent.parent.parent / "models"


def _report_path(season: int) -> Path:
    return MODELS_DIR / f"tunneling_v1_report_{season}.json"


def _pitchers_path(season: int) -> Path:
    return MODELS_DIR / f"tunneling_v1_pitchers_{season}.json"


@router.get("/report")
def get_report(season: int):
    """League-wide summary for one season: methodology parameters, split-half
    reliability, outcome-correlation validity checks, the sequential
    same-at-bat test, and worked examples. Regenerated by re-running
    `python build_tunneling_report.py [season]`."""
    path = _report_path(season)
    if not path.exists():
        raise HTTPException(404, f"No tunneling report for season {season} - run build_tunneling_report.py first")
    return json.loads(path.read_text())


@router.get("/pitcher/{pitcher_id}")
def get_pitcher_detail(pitcher_id: int, season: int):
    """One pitcher's pair-level detail for one season: every qualifying
    pitch-type pair with release/tunnel/plate distances and the resulting
    tunneling_plus (plus its two components and whether it's an FF/SI
    anchor pair)."""
    path = _pitchers_path(season)
    if not path.exists():
        raise HTTPException(404, f"No tunneling report for season {season} - run build_tunneling_report.py first")
    all_pitchers = json.loads(path.read_text())
    detail = all_pitchers.get(str(pitcher_id))
    if not detail:
        raise HTTPException(404, f"No tunneling detail for pitcher {pitcher_id} in {season} (may not qualify)")
    return detail
