"""
/api/stuff-model/* - serves the Stuff+ v2 model's training report (from
`train_stuff_model.py`, read straight off disk) and per-pitcher SHAP
breakdowns, for the "model internals" page (`stuff-model.html`). This
exists so the model isn't a black box: every number the page shows traces
back to either the offline training report or a live SHAP computation
against the actual production model.
"""
import json
import sys
from pathlib import Path

from fastapi import APIRouter, Depends, HTTPException

sys.path.insert(0, str(Path(__file__).resolve().parent.parent.parent))

from stuff_model import _raw_predictions, pitcher_shap_breakdown

from api.cache import ttl_cache
from api.db import get_conn

router = APIRouter(prefix="/api/stuff-model")

REPORT_PATH = Path(__file__).resolve().parent.parent.parent / "models" / "stuff_plus_v2_report.json"
PREDICTIVE_VALIDITY_PATH = Path(__file__).resolve().parent.parent.parent / "models" / "predictive_validity_report.json"


@ttl_cache()
def _raw_predictions_table(conn, season):
    """League-wide raw predictions for one season - cached because scoring
    every pitch in a season is the expensive part; per-pitcher SHAP lookups
    below reuse this instead of re-scoring the whole league each time."""
    return _raw_predictions(conn, season)


@router.get("/report")
def get_report():
    """The static offline training report: cross-validation metrics per
    held-out season, global feature importance (gain + SHAP), and a few
    worked example pitches. Regenerated by re-running
    `python train_stuff_model.py`, not by anything in the running API."""
    if not REPORT_PATH.exists():
        raise HTTPException(404, "No training report found - run train_stuff_model.py first")
    return json.loads(REPORT_PATH.read_text())


@router.get("/predictive-validity")
def get_predictive_validity():
    """v1-vs-v2 head-to-head: does each pitcher's Stuff+ from one season
    predict their REAL results the next season? Generated by
    `python validate_predictive_power.py` (not run automatically - it
    trains a separate one-off model, several minutes), which is also
    where the full methodology is documented."""
    if not PREDICTIVE_VALIDITY_PATH.exists():
        raise HTTPException(404, "No predictive-validity report found - run validate_predictive_power.py first")
    return json.loads(PREDICTIVE_VALIDITY_PATH.read_text())


@router.get("/pitcher/{pitcher_id}")
def get_pitcher_breakdown(pitcher_id: int, season: int, conn=Depends(get_conn)):
    """Per-pitch-type SHAP attribution for one pitcher/season: which
    inputs are driving each of their pitch types' Stuff+ rating, in
    Stuff+-point units so it reads on the same scale as the rest of the
    site."""
    league = _raw_predictions_table(conn, season)
    if league.empty:
        raise HTTPException(404, f"No scored pitches for season {season}")
    breakdown = pitcher_shap_breakdown(conn, season, pitcher_id, league)
    if not breakdown:
        raise HTTPException(404, f"No pitches found for pitcher {pitcher_id} in {season}")
    return breakdown
