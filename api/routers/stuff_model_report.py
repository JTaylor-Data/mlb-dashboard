@router.get("/leaderboard")
def get_stuff_leaderboard(
    season: int = Query(default=2026, ge=2016, le=2026, description="Season (2016–2026)"),
    pitch_type: str = Query(default=None, description="Pitch type filter (e.g. FF, SL, CU); omit for overall"),
    n: int = Query(default=15, ge=1, le=50, description="Number of entries per side"),
    direction: str = Query(default="both", description="top, bottom, or both"),
    conn=Depends(get_conn),
):
    """Top/bottom Stuff+ leaderboard. Overall (usage-weighted) or per pitch type.
    Season range 2016–2026. 2020 entries carry asterisk note.
    Overall: >= 200 pitches. Per-type: >= 100 pitches of that type."""
    if pitch_type:
        result = _stuff_leaderboard_by_type(conn, season, pitch_type.upper(), n)
    else:
        result = _stuff_leaderboard_overall(conn, season, n)
    if direction == "top":
        result = {k: v for k, v in result.items() if k != "bottom"}
    elif direction == "bottom":
        result = {k: v for k, v in result.items() if k != "top"}
    return result


@router.get("/predictive-validity")
def get_predictive_validity():
    """Does each pitcher's Stuff+ v3 (the live model) from one season
    predict their REAL results the next season? A model trained without
    2024 scores 2024 pitches, correlated against real 2025 outcomes -
    honest out-of-sample, not in-sample fit. Generated by
    `python training/stuff_v3_predictive_validity.py` (not run
    automatically - it trains a separate one-off model, several minutes)."""
    if not PREDICTIVE_VALIDITY_PATH.exists():
        raise HTTPException(404, "No predictive-validity report found - run training/stuff_v3_predictive_validity.py first")
    return json.loads(PREDICTIVE_VALIDITY_PATH.read_text())


@ttl_cache()
def _stuff_pitch_types_cached(conn, season):
    """Qualifying pitch types for a season (>= leaderboard_min_pitches_per_type)."""
    table = compute_stuff_plus(conn, season)
    if table.empty:
        return []
    g = table.reset_index()
    counts = g.groupby("pitch_type")["n_pitches"].sum().reset_index()
    counts = counts[counts["n_pitches"] >= LEADERBOARD_MIN_PITCHES_PER_TYPE]
    counts = counts.sort_values("n_pitches", ascending=False)
    return [
        {"pitch_type": str(r.pitch_type), "n_qualifying_pitchers": int(
            len(g[(g["pitch_type"] == r.pitch_type) & (g["n_pitches"] >= LEADERBOARD_MIN_PITCHES_PER_TYPE)])
        ), "total_pitches": int(r.n_pitches)}
        for r in counts.itertuples()
    ]


